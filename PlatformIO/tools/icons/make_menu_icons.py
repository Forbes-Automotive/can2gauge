#!/usr/bin/env python3
"""Mode-menu / settings icons (tools/icons/menu_icons.js) -> LVGL A8 layer bitmaps for the firmware.

The icons are the concept's canvas drawings (docs/ui-concept), so the exact way to rasterise them is a browser: this
opens menu_icons_export.html in headless Edge (or Chrome), which draws every icon once per colour layer (theme accent,
second accent, muted grey, line grey), crops each layer to its ink and hands back the alpha. Each layer becomes an A8
image; the glass stacks them in the order given (track grey, grey, second accent, accent) with image_recolor in the
palette colours, so the two-colour look follows the theme.

    python tools/icons/make_menu_icons.py            -> lib/GaugeUI/src/MenuIcons.cpp / .h
    set CAN2GAUGE_BROWSER=path\\to\\chrome.exe       if Edge isn't in its usual place
Standard library only.
"""
import base64
import html
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "lib", "GaugeUI", "src")
BROWSERS = [os.environ.get("CAN2GAUGE_BROWSER", ""),
            r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
            r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
            r"C:\Program Files\Google\Chrome\Application\chrome.exe"]
ROLE = {"acc": "MIR_ACC", "acc2": "MIR_ACC2", "muted": "MIR_MUTED", "line": "MIR_LINE"}


def render():
    browser = next((b for b in BROWSERS if b and os.path.isfile(b)), None)
    if not browser:
        sys.exit("no Edge / Chrome found - set CAN2GAUGE_BROWSER")
    url = "file:///" + os.path.join(HERE, "menu_icons_export.html").replace("\\", "/")
    with tempfile.TemporaryDirectory() as prof:
        dom = subprocess.run([browser, "--headless=new", "--disable-gpu", "--force-device-scale-factor=1",
                              "--virtual-time-budget=15000", "--user-data-dir=" + prof, "--dump-dom", url],
                             capture_output=True, text=True, encoding="utf-8", timeout=120).stdout
    m = re.search(r'<pre id="out">(.*?)</pre>', dom, re.S)
    if not m or m.group(1).strip() in ("", "pending"):
        sys.exit("the export page did not finish:\n" + dom[:500])
    return json.loads(html.unescape(m.group(1)))


def main():
    icons = render()
    names = list(icons)
    h = ["#pragma once",
         "// generated by tools/icons/make_menu_icons.py from tools/icons/menu_icons.js - do not edit",
         "// the mode-menu / settings icons of docs/ui-concept: one A8 bitmap per colour layer, drawn at scale 1.15",
         "#include <lvgl.h>", "",
         "enum menuIcon_t : uint8_t", "{"]
    h += ["  MI_%s," % n.upper() for n in names]
    h += ["  MI_COUNT", "};", "",
          "enum menuIconRole_t : uint8_t", "{",
          "  MIR_ACC = 0, // theme accent", "  MIR_ACC2,    // second accent", "  MIR_MUTED,   // secondary grey",
          "  MIR_LINE,    // track grey", "};", "",
          "struct MenuIconLayer", "{", "  const lv_image_dsc_t *img;",
          "  int16_t dx, dy; // the layer's centre relative to the icon's centre (px)", "  uint8_t role;   // menuIconRole_t", "};",
          "struct MenuIcon", "{", "  const MenuIconLayer *layers;", "  uint8_t count;", "};", "",
          "const MenuIcon &menuIcon(uint8_t icon); // an empty icon for an unknown id", ""]
    c = ["// generated by tools/icons/make_menu_icons.py from tools/icons/menu_icons.js - do not edit",
         '#include "MenuIcons.h"', ""]
    total = 0
    for n in names:
        for i, L in enumerate(icons[n]):
            a = base64.b64decode(L["alpha"])
            total += len(a)
            sym = "mi_%s_%d" % (n, i)
            c.append("static const uint8_t %s_map[%d] = {" % (sym, len(a)))
            for j in range(0, len(a), 32):
                c.append("    " + ",".join("0x%02x" % v for v in a[j:j + 32]) + ",")
            c.append("};")
            c.append("static const lv_image_dsc_t %s = {" % sym)
            c.append("    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = %d, .h = %d, .stride = %d},"
                     % (L["w"], L["h"], L["w"]))
            c.append("    .data_size = %d," % len(a))
            c.append("    .data = %s_map," % sym)
            c.append("};")
        c.append("static const MenuIconLayer mi_%s_layers[] = {%s};" % (
            n, ", ".join("{&mi_%s_%d, %d, %d, %s}" % (n, i, round(L["dx"]), round(L["dy"]), ROLE[L["role"]])
                         for i, L in enumerate(icons[n])) or "{NULL, 0, 0, 0}"))
        c.append("")
    c.append("static const MenuIcon icons[MI_COUNT] = {")
    c += ["    {mi_%s_layers, %d}," % (n, len(icons[n])) for n in names]
    c.append("};")
    c.append("static const MenuIcon none = {NULL, 0};")
    c.append("")
    c.append("const MenuIcon &menuIcon(uint8_t icon) { return icon < MI_COUNT ? icons[icon] : none; }")
    with open(os.path.join(OUT, "MenuIcons.h"), "w", newline="\n") as f:
        f.write("\n".join(h))
    with open(os.path.join(OUT, "MenuIcons.cpp"), "w", newline="\n") as f:
        f.write("\n".join(c) + "\n")
    print("wrote %d menu icons (%d layers, %d kB of A8) -> lib/GaugeUI/src/MenuIcons.{h,cpp}"
          % (len(names), sum(len(v) for v in icons.values()), total // 1024))


if __name__ == "__main__":
    main()
