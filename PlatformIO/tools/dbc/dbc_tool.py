BO = re.compile(r"^BO_ (\d+) (\w+)\s*:\s*(\d+) (\w+)", re.M)
SG = re.compile(r"^ SG_ (\w+)\s*(\w*)\s*:\s*(\d+)\|(\d+)@([01])([+-]) \(([^,]+),([^)]+)\) \[([^|]*)\|([^\]]*)\] \"([^\"]*)\"", re.M)


def parse_dbc(text):
    """-> {id: {"name", "dlc", "tx", "signals": [names]}} (id with the extended-frame bit 31 cleared, "ext" flag)"""
    msgs = {}
    cur = None
    for line in text.splitlines():
        m = BO.match(line)
        if m:
            raw = int(m.group(1))
            ext = bool(raw & 0x80000000)
            mid = raw & 0x1FFFFFFF
            cur = {"name": m.group(2), "dlc": int(m.group(3)), "tx": m.group(4), "ext": ext, "signals": []}
            msgs[mid] = cur
            continue
        if cur is not None:
            s = SG.match(line)
            if s:
                cur["signals"].append(s.group(1))
            elif line.strip() == "" or not line.startswith(" "):
                cur = None
    return msgs


