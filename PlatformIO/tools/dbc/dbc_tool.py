def pack():
    import gzip
    dst = os.path.join(ROOT, "data", "dbc")
    os.makedirs(dst, exist_ok=True)
    for f in os.listdir(dst):
        os.remove(os.path.join(dst, f))
    idx = json.loads(read(os.path.join(OUT, "index.json")))["dbcs"]
    slim, fps, total = [], {}, 0
    for e in idx:
        src = os.path.join(OUT, *(e["english"] or e["file"]).split("/"))
        # 0.28.0: an opendbc file gets the gauge's overlay (GaugeKey / value labels) merged in
        dbc = read_dbc_bytes(src) + overlay_text(e["name"], bool(e["english"]))
        body, attributes = c2d_text(dbc)
        if not any(l.startswith("M\t") for l in body):
            continue
        # header, version 2: name, bus speed (0 = not given), relocatable (the ECU's base id can be moved)
        text = "C2D\t2\t%s\t%d\t%d\n%s\n" % (e["name"], attributes["bus"], attributes["reloc"], "\n".join(body))
        out = os.path.join(dst, e["name"] + ".c2d.gz")
        with gzip.open(out, "wb", compresslevel=9) as g:
            g.write(text.encode("utf-8"))
        total += os.path.getsize(out)
        msgs = [m for m in e["messages"]]
        slim.append({"name": e["name"], "make": MAKE_NAMES.get(e["name"], e["make"]), "kind": e["kind"], "cars": e["cars"][:12],
                     "desc": e.get("desc") or PLATFORMS.get(e["name"], ""), "en": bool(e["english"]), "messages": len(msgs),
                     # 0.28.0: the gauge's own DBCs and the opendbc ones it has overlays for feed gauge signals directly
                     "gauge": e.get("source") == "gauge", "keys": len(attributes["keys"]), "bus": attributes["bus"],
                     "reloc": attributes["reloc"]})
        fps[e["name"]] = [[m["id"], m["dlc"]] for m in msgs if not m["ext"] and m["id"] <= 0x7FF]
    for name, obj in (("index.json.gz", {"dbcs": slim}), ("fingerprints.json.gz", fps)):
        with gzip.open(os.path.join(dst, name), "wb", compresslevel=9) as g:
            g.write(json.dumps(obj, separators=(",", ":")).encode("utf-8"))
        total += os.path.getsize(os.path.join(dst, name))
    print("pack: %d DBCs -> data/dbc/ (%d kB gzipped, with index + fingerprints)" % (len(slim), total // 1024))


