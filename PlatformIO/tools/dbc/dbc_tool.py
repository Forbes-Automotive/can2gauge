def _norm(w):
    return (w.lower().replace("ä", "ae").replace("ö", "oe").replace("ü", "ue").replace("ß", "ss"))


_GLOSS_KEYS = {k for k in GLOSSARY if len(k) >= 3}
_LINK = ("s", "n", "en", "e", "es")  # Fugen elements between compound parts


def split_compound(w):
    """minimum-part segmentation of w into glossary stems (Fugen-s / -n allowed between parts), or None"""
    n = len(w)
    best = [None] * (n + 1)  # best[i] = (parts, links, [stems]) for w[:i]
    best[0] = (0, 0, [])
    for i in range(n):
        if best[i] is None:
            continue
        starts = [(i, 0)] + [(i + len(l), 1) for l in _LINK if i > 0 and w.startswith(l, i)]
        for j0, link in starts:
            for j in range(j0 + 3, n + 1):
                stem = w[j0:j]
                if stem in _GLOSS_KEYS:
                    cand = (best[i][0] + 1, best[i][1] + link, best[i][2] + [stem])
                    if best[j] is None or cand[:2] < best[j][:2]:
                        best[j] = cand
    return best[n][2] if best[n] else None


class Translator:
    def __init__(self):
        self.missing = Counter()

    def word(self, w):
        """one CamelCase / underscore piece -> English (or unchanged); records German leftovers"""
        if not w or w.isdigit() or not re.search(r"[A-Za-z]", w):
            return w
        k = _norm(w)
        if k in KEEP:
            return w
        if k in GLOSSARY:
            t = GLOSSARY[k]
            return t.upper() if (w.isupper() and len(w) > 1 and len(t) <= 4) else t
        parts = split_compound(k) if len(k) >= 6 else None
        if parts:
            return "".join(GLOSSARY[p] for p in parts)
        if len(k) > 2:
            self.missing[k] += 1
        return w

    def ident(self, name):
        """identifier: translate each '_' part; CamelCase runs inside a part are translated piecewise"""
        out = []
        for part in name.split("_"):
            if part == "":
                out.append(part)
                continue
            pieces = re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-zäöüß]+|\d+|[^A-Za-z\d]+", part)
            if len(pieces) > 1 and all(p.isalpha() for p in pieces) and _norm(part) in GLOSSARY:
                pieces = [part]  # a whole-word hit beats splitting "OelDruck"
            out.append("".join(self.word(p) for p in pieces))
        res = "_".join(out)
        res = re.sub(r"[^A-Za-z0-9_]", "", res)
        if not res or res[0].isdigit():
            res = "S_" + res
        return res

    def text(self, s):
        """value-table text: words split on '_' / spaces, the separators kept"""
        return re.sub(r"[A-Za-zÄÖÜäöüß]+", lambda m: self.ident(m.group(0)), s)


def german_score(text):
    names = re.findall(r"^ SG_ (\w+)", text, re.M) + re.findall(r"^BO_ \d+ (\w+)", text, re.M)
    if not names:
        return 0.0
    # 5+ letter German stems only: short ones ("rad", "art", "alt") are English too. On opendbc this puts the VW / Audi
    # files at 0.47-0.57 and every other DBC at 0.15 or less
    hits = sum(1 for n in names if any(len(k) >= 5 and k in GLOSSARY and k not in KEEP
                                       for k in (_norm(t) for t in re.findall(r"[A-Z]?[a-z]+", n))))
    return hits / len(names)


def translate_dbc(text, tr):
    msg_map, sig_map = {}, {}  # old msg name -> new; (id, old sig) -> new
    used_msgs = set()
    cur = None
    out_lines = []
    for line in text.split("\n"):
        m = BO.match(line)
        if m:
            cur = int(m.group(1))
            new = tr.ident(m.group(2))
            base, k = new, 2
            while new in used_msgs:
                new, k = "%s_%d" % (base, k), k + 1
            used_msgs.add(new)
            msg_map[m.group(2)] = new
            sig_map[(cur, None)] = set()
            line = line[:m.start(2)] + new + line[m.end(2):]
        elif cur is not None and line.startswith(" SG_ "):
            s = re.match(r" SG_ (\w+)", line)
            old = s.group(1)
            new = tr.ident(old)
            base, k = new, 2
            while new in sig_map[(cur, None)]:
                new, k = "%s_%d" % (base, k), k + 1
            sig_map[(cur, None)].add(new)
            sig_map[(cur, old)] = new
            line = " SG_ " + new + line[s.end(1):]
        elif not line.startswith(" "):
            cur = None
        out_lines.append(line)
    out = "\n".join(out_lines)

    def sig(mid, name):
        return sig_map.get((int(mid), name), name)

    # references to signals: CM_ SG_, VAL_, SG_MUL_VAL_, SIG_VALTYPE_, BA_ "x" SG_; comments keep the German name
    commented = set()

    def cm_sg(m):
        mid, name, body = m.group(1), m.group(2), m.group(3)
        new = sig(mid, name)
        commented.add((int(mid), name))
        tag = " [DE: %s]" % name if new != name else ""
        return 'CM_ SG_ %s %s "%s%s";' % (mid, new, body, tag)

    out = re.sub(r'CM_ SG_ (\d+) (\w+) "(.*?)";', cm_sg, out, flags=re.S)

    def val(m):
        mid, name, rest = m.group(1), m.group(2), m.group(3)
        rest = re.sub(r'"(.*?)"', lambda q: '"%s"' % tr.text(q.group(1)), rest)
        return "VAL_ %s %s%s" % (mid, sig(mid, name), rest)

    out = re.sub(r"^VAL_ (\d+) (\w+)(.*?;)", val, out, flags=re.M)
    out = re.sub(r"^SG_MUL_VAL_ (\d+) (\w+) (\w+)",
                 lambda m: "SG_MUL_VAL_ %s %s %s" % (m.group(1), sig(m.group(1), m.group(2)), sig(m.group(1), m.group(3))),
                 out, flags=re.M)
    out = re.sub(r"^SIG_VALTYPE_ (\d+) (\w+)", lambda m: "SIG_VALTYPE_ %s %s" % (m.group(1), sig(m.group(1), m.group(2))),
                 out, flags=re.M)
    out = re.sub(r'^(BA_ "\w+" SG_ )(\d+) (\w+)', lambda m: "%s%s %s" % (m.group(1), m.group(2), sig(m.group(2), m.group(3))),
                 out, flags=re.M)
    # message comments keep the German message name too; renamed signals without a comment get one with it
    bo_old = {int(m.group(1)): m.group(2) for m in BO.finditer(text)}
    out = re.sub(r'CM_ BO_ (\d+) "(.*?)";',
                 lambda m: 'CM_ BO_ %s "%s%s";' % (m.group(1), m.group(2),
                                                   " [DE: %s]" % bo_old.get(int(m.group(1)), "") if msg_map.get(bo_old.get(int(m.group(1)), "")) not in (None, bo_old.get(int(m.group(1)))) else ""),
                 out, flags=re.S)
    extra = []
    for (mid, old), new in sig_map.items():
        if old is not None and new != old and (mid, old) not in commented:
            extra.append('CM_ SG_ %d %s "[DE: %s]";' % (mid, new, old))
    for mid, old in bo_old.items():
        if msg_map.get(old) != old and not re.search(r"CM_ BO_ %d " % mid, out):
            extra.append('CM_ BO_ %d "[DE: %s]";' % (mid, old))
    if extra:
        out = out.rstrip("\n") + "\n" + "\n".join(extra) + "\n"
    names = {"messages": {o: n for o, n in msg_map.items() if o != n},
             "signals": {"%d:%s" % (mid, o): n for (mid, o), n in sig_map.items() if o is not None and o != n}}
    return out, names


def verify(orig, new):
    """same messages, same signal counts, every signal name a valid identifier and unique within its message"""
    a, b = parse_dbc(orig), parse_dbc(new)
    assert a.keys() == b.keys(), "message ids differ"
    for mid in a:
        assert len(a[mid]["signals"]) == len(b[mid]["signals"]), "signal count differs in %d" % mid
        assert len(set(b[mid]["signals"])) == len(b[mid]["signals"]), "duplicate signal in %d" % mid
        for s in b[mid]["signals"]:
            assert re.fullmatch(r"[A-Za-z_]\w*", s), "bad name %s" % s
    def dangling(text, msgs):
        known = {(mid, s) for mid in msgs for s in msgs[mid]["signals"]}
        return [(m, s) for m, s in re.findall(r"^VAL_ (\d+) (\w+)", text, re.M) if (int(m) & 0x1FFFFFFF, s) not in known]

    # a few upstream DBCs carry VAL_ lines for signals their message doesn't have; renaming must not add any
    bad_a, bad_b = dangling(orig, a), dangling(new, b)
    assert len(bad_b) <= len(bad_a), "VAL_ for unknown signals: %s" % bad_b[:5]
    return bad_a


def translate():
    src_dirs = ["current", "generated", "legacy"]
    tr = Translator()
    done = []
    for d in src_dirs:
        p = os.path.join(OUT, "opendbc", d)
        if not os.path.isdir(p):
            continue
        for f in sorted(os.listdir(p)):
            if not f.endswith(".dbc"):
                continue
            text = read(os.path.join(p, f))
            if german_score(text) < 0.3:
                continue
            new, names = translate_dbc(text, tr)
            upstream = verify(text, new)
            if upstream:
                print("translate: %s has %d VAL_ line(s) for signals it does not define (upstream, kept as is)" % (f, len(upstream)))
            new = new.rstrip("\n") + ('\nCM_ "English names by can2gauge tools/dbc/dbc_tool.py from opendbc %s (MIT); the '
                                      'original German names are in the comments as [DE: ...]";\n' % f)
            write(os.path.join(OUT, "opendbc", "en", f), new)
            write(os.path.join(OUT, "opendbc", "en", f.replace(".dbc", ".names.json")), json.dumps(names, indent=1, ensure_ascii=False))
            n_msg, n_sig = len(names["messages"]), len(names["signals"])
            done.append((f, n_msg, n_sig))
            print("translate: %-28s %4d message and %5d signal names translated" % (f, n_msg, n_sig))
    rep = ["# German stems / words left untranslated (add them to tools/dbc/glossary_de_en.py), most frequent first", ""]
    rep += ["%-40s %d" % (w, c) for w, c in tr.missing.most_common()]
    write(os.path.join(OUT, "opendbc", "en", "untranslated.txt"), "\n".join(rep) + "\n")
    total = sum(tr.missing.values())
    print("translate: %d DBCs; %d distinct leftover words (%d occurrences) -> dbc/opendbc/en/untranslated.txt"
          % (len(done), len(tr.missing), total))


