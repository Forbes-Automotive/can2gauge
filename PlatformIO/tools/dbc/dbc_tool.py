INCLUDE = re.compile(r'CM_ "IMPORT (.*?)";\n')


def expand_includes(src_dir, filename, extra=None):
    """opendbc's generator: a template's CM_ "IMPORT x.dbc" lines pull x.dbc in front of the template. extra = files
    made by opendbc's script generators ({filename: content}), used before the disk"""
    extra = extra or {}
    text = extra[filename] if filename in extra else read(os.path.join(src_dir, filename))
    parts = ['CM_ "AUTOGENERATED FILE, DO NOT EDIT";\n']
    for inc in INCLUDE.findall(text):
        parts.append('\n\nCM_ "Imported file %s starts here";\n' % inc)
        parts.append(extra[inc] if inc in extra else read(os.path.join(src_dir, inc)))
    parts.append('\nCM_ "%s starts here";\n' % filename)
    parts.append(INCLUDE.sub("", text))
    return "".join(parts)


def fetch():
    if os.path.isdir(os.path.join(CACHE, ".git")):
        run(["git", "fetch", "-q", "origin"], CACHE)
        run(["git", "reset", "-q", "--hard", "FETCH_HEAD"], CACHE)
    else:
        os.makedirs(os.path.dirname(CACHE), exist_ok=True)
        run(["git", "clone", "-q", "--filter=blob:none", OPENDBC_URL, CACHE])
    commit = run(["git", "log", "-1", "--format=%H %cs"], CACHE).strip()
    dbc_dir = os.path.join(CACHE, "opendbc", "dbc")
    dst = os.path.join(OUT, "opendbc")
    n_cur = n_gen = n_leg = 0
    current = set()
    for f in sorted(os.listdir(dbc_dir)):
        if f.endswith(".dbc"):
            write(os.path.join(dst, "current", f), read(os.path.join(dbc_dir, f)))
            current.add(f)
            n_cur += 1
    # generator: templates (files starting with "_" are include-only) plus what opendbc's script generators make
    # (generator/<make>/*.py, generate() -> {filename: content}; they only need the standard library)
    gen_root = os.path.join(dbc_dir, "generator")
    skipped_scripts = []
    sys.path.insert(0, CACHE)
    for sub in sorted(os.listdir(gen_root)):
        sd = os.path.join(gen_root, sub)
        if not os.path.isdir(sd):
            continue
        extra = {}
        for f in sorted(os.listdir(sd)):
            if f.endswith(".py") and not f.startswith("test_") and f != "__init__.py":
                try:
                    mod = importlib.import_module("opendbc.dbc.generator.%s.%s" % (sub, f[:-3]))
                    if hasattr(mod, "generate"):
                        extra.update(mod.generate())
                except Exception as e:  # noqa: BLE001 - report it and carry on
                    skipped_scripts.append("%s/%s (%s)" % (sub, f, e))
        names = {f for f in os.listdir(sd) if f.endswith(".dbc")} | set(extra)
        for f in sorted(n for n in names if not n.startswith("_")):
            name = f.replace(".dbc", "_generated.dbc")
            try:
                text = expand_includes(sd, f, extra)
            except FileNotFoundError as e:
                skipped_scripts.append("%s/%s (%s)" % (sub, f, e))
                continue
            write(os.path.join(dst, "generated", name), text)
            current.add(name)
            n_gen += 1
    # DBCs removed from master: last version before the deleting commit (renames are not deletions: vw_golf_mk4.dbc
    # became vw_pq.dbc in 2025 and is in current/)
    log = run(["git", "log", "--diff-filter=D", "--name-only", "--format=@@%H"], CACHE)
    commit_of = {}
    cur_commit = None
    for line in log.splitlines():
        if line.startswith("@@"):
            cur_commit = line[2:]
        elif line.endswith(".dbc"):
            commit_of.setdefault(line, cur_commit)  # newest deletion first
    for path, c in sorted(commit_of.items()):
        base = os.path.basename(path)
        if base.startswith("_") or base.endswith("_generated.dbc") or base == "test.dbc" or base in current:
            continue
        if "/generator/" in "/" + path:
            continue  # a template needs its includes from that era; the generated output was never committed
        try:
            text = run(["git", "show", "%s^:%s" % (c, path)], CACHE)
        except subprocess.CalledProcessError:
            continue
        write(os.path.join(dst, "legacy", base), text)
        n_leg += 1
    write(os.path.join(dst, "SOURCE.md"),
          "# opendbc DBC files\n\nFrom %s at commit `%s`.\n\nLicence: MIT (Copyright (c) 2020, Comma.ai, Inc.), see "
          "LICENSE in this folder.\n\n- current/: %d DBCs on master\n- generated/: %d built from the generator templates "
          "(include expansion + opendbc's script generators)\n- legacy/: %d DBCs removed from master (last version "
          "before removal)\n- en/: English translations of the German VW / Audi DBCs (tools/dbc/dbc_tool.py translate)"
          "\n\nNot generated: %s\n"
          % (OPENDBC_URL, commit, n_cur, n_gen, n_leg, ", ".join(skipped_scripts) or "none - everything opendbc generates is here"))
    write(os.path.join(dst, "LICENSE"), read(os.path.join(CACHE, "LICENSE")))
    print("fetch: opendbc %s -> %d current, %d generated, %d legacy%s" % (
        commit, n_cur, n_gen, n_leg, ("; not generated: " + ", ".join(skipped_scripts)) if skipped_scripts else ""))


