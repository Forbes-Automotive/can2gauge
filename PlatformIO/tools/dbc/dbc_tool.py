# ======================================================================================================================
# gauge attributes (docs/CAN_DBC_plan.md section 1): which gauge signal a DBC signal feeds, how sure the gauge can be of
# an ECU. Standard DBC attributes, so the files stay normal DBCs that CANdb++ / cantools / SavvyCAN open and keep.
# ======================================================================================================================
GAUGE_KEY = re.compile(r'^BA_ "GaugeKey" SG_ (\d+) (\w+) "([^"]*)"\s*;', re.M)
GAUGE_PRIO = re.compile(r'^BA_ "GaugePriority" SG_ (\d+) (\w+) (\d+)\s*;', re.M)
GAUGE_BUS = re.compile(r'^BA_ "GaugeBusSpeed" (\d+)\s*;', re.M)
GAUGE_RELOC = re.compile(r'^BA_ "GaugeRelocatable" (\d+)\s*;', re.M)
GAUGE_CHECK = re.compile(r'^BA_ "GaugeCheck" BO_ (\d+) "(\w+) (\S+) (\S+)"\s*;', re.M)
VAL_LINE = re.compile(r'^VAL_ (\d+) (\w+) (.*?);', re.M)
VAL_PAIR = re.compile(r'(-?\d+) "([^"]*)"')


def message_id(raw):
    """a DBC id as the gauge keeps it: 29 bits, bit 31 = extended"""
    raw = int(raw)
    return (raw & 0x1FFFFFFF) | (0x80000000 if raw & 0x80000000 else 0)


def gauge_attributes(text):
    """the Gauge* attributes and value labels of a DBC. A later line wins, so an overlay replaces the DBC's own VAL_"""
    keys, prios, labels, checks = {}, {}, {}, {}
    for m in GAUGE_KEY.finditer(text):
        keys[(message_id(m.group(1)), m.group(2))] = m.group(3)
    for m in GAUGE_PRIO.finditer(text):
        prios[(message_id(m.group(1)), m.group(2))] = int(m.group(3))
    for m in VAL_LINE.finditer(text):
        labels[(message_id(m.group(1)), m.group(2))] = [(int(v), t) for v, t in VAL_PAIR.findall(m.group(3))]
    for m in GAUGE_CHECK.finditer(text):
        checks.setdefault(message_id(m.group(1)), []).append((m.group(2), m.group(3), m.group(4)))
    bus = GAUGE_BUS.findall(text)
    reloc = GAUGE_RELOC.findall(text)
    return {"keys": keys, "prios": prios, "labels": labels, "checks": checks,
            "bus": int(bus[-1]) if bus else 0, "reloc": int(reloc[-1]) if reloc else 0}


def overlay_text(name, english):
    """dbc/gauge/overlays/<name>.overlay.dbc: the gauge's BA_ / VAL_ lines for an opendbc file (opendbc's own files are
    never edited). Written with opendbc's own (German) names; for the English copy they're renamed through
    opendbc/en/<name>.names.json ("<id>:<German>" -> English)"""
    path = os.path.join(OUT, "gauge", "overlays", name + ".overlay.dbc")
    if not os.path.isfile(path):
        return ""
    text = read(path)
    names_path = os.path.join(OUT, "opendbc", "en", name + ".names.json")
    if english and os.path.isfile(names_path):
        signal_names = json.loads(read(names_path)).get("signals", {})

        def rename(m):
            new = signal_names.get("%d:%s" % (int(m.group(2)), m.group(3)), m.group(3))
            return m.group(1) + new

        text = re.sub(r'((?:SG_|^VAL_) (\d+) )(\w+)', rename, text, flags=re.M)
        text = re.sub(r'(BO_ (\d+) ")(\w+)', rename, text)
    return "\n" + text


def c2d_text(text):
    """-> the gauge's compact form (include/can2gauge_CanMon.h): C2D / M / S lines, tab separated. 0.28.0 (version 2):
    S lines also carry the signal's GaugeKey and GaugePriority, V lines its value labels (for a keyed signal), K lines a
    message's GaugeCheck ranges. Returns (lines, attributes)."""
    attributes = gauge_attributes(text)
    def clean(s, n):
        s = s.replace("\t", " ").replace("\ufffd", "\u00b0")
        s = "".join(c if (32 <= ord(c) < 127 or c == "\u00b0") else "?" for c in s)
        return s.strip()[:n]

    lines = []
    cur = False
    mid = 0
    for line in text.splitlines():
        m = BO.match(line)
        if m:
            raw = int(m.group(1))
            if (raw & 0x1FFFFFFF) == 0x1FFFFFFF or m.group(2) == "VECTOR__INDEPENDENT_SIG_MSG":
                cur = False  # the DBC editor's placeholder for unassigned signals
                continue
            mid = message_id(raw)
            lines.append("M\t%d\t%d\t%s" % (mid, int(m.group(3)), clean(m.group(2), 39)))
            for sig, lo, hi in attributes["checks"].get(mid, []):  # GaugeCheck: this signal must sit in lo..hi
                lines.append("K\t%s\t%s\t%s" % (clean(sig, 39), lo, hi))
            cur = True
            continue
        if not cur:
            continue
        s = SG.match(line)
        if s:
            mux = s.group(2)
            muxv = -2 if mux == "M" else int(re.match(r"m(\d+)", mux).group(1)) if re.match(r"m(\d+)", mux) else -1
            flags = (1 if s.group(5) == "1" else 0) | (2 if s.group(6) == "-" else 0)
            key = attributes["keys"].get((mid, s.group(1)), "")
            prio = attributes["prios"].get((mid, s.group(1)), 0)
            lines.append("S\t%s\t%s\t%s\t%d\t%s\t%s\t%s\t%d\t%s\t%d" % (
                clean(s.group(1), 39), s.group(3), s.group(4), flags, s.group(7).strip(), s.group(8).strip(),
                clean(unit_of(s.group(11)), 9), muxv, clean(key, 15), prio))
            if key:  # value labels only matter for a signal that feeds the gauge (gear / selector / "no value" codes)
                for value, label in attributes["labels"].get((mid, s.group(1)), []):
                    lines.append("V\t%d\t%s" % (value, clean(label, 15)))
        elif line.strip() == "" or not line.startswith(" "):
            cur = False
    return lines, attributes


