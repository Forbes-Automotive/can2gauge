def index():
    cars = car_platforms()
    idx, fps = [], {}
    for d, f, path in all_dbc_files():
        if d == "en":
            continue  # same ids as the German original; the index points at the English copy instead
        name = f[:-4]
        msgs = parse_dbc(read(path))
        if d == "gauge":
            # 0.28.0: one of the gauge's own DBCs (dbc/gauge/), no translation, no openpilot car list
            make, desc = GAUGE_DBCS.get(name, (name.split("_")[0], ""))
            idx.append({"name": name, "file": "gauge/%s" % f, "english": None, "source": "gauge", "kind": "gauge",
                        "make": make, "desc": desc, "cars": [],
                        "messages": [{"id": mid, "ext": m["ext"], "dlc": m["dlc"], "name": m["name"], "en": None,
                                      "signals": len(m["signals"])} for mid, m in sorted(msgs.items())]})
            fps[name] = sorted([mid, m["dlc"]] for mid, m in msgs.items() if not m["ext"] and mid <= 0x7FF)
            continue
        en_path = os.path.join(OUT, "opendbc", "en", f)
        en = parse_dbc(read(en_path)) if os.path.isfile(en_path) else None
        make = name.split("_")[0]
        entry = {
            "name": name, "file": "opendbc/%s/%s" % (d, f), "english": ("opendbc/en/%s" % f) if en else None,
            "source": "opendbc", "kind": d, "make": make, "cars": sorted(cars.get(name, [])),
            "messages": [{"id": mid, "ext": m["ext"], "dlc": m["dlc"], "name": m["name"],
                          "en": en[mid]["name"] if en and mid in en else None, "signals": len(m["signals"])}
                         for mid, m in sorted(msgs.items())],
        }
        idx.append(entry)
        fps[name] = sorted([mid, m["dlc"]] for mid, m in msgs.items() if not m["ext"] and mid <= 0x7FF)
    write(os.path.join(OUT, "index.json"), json.dumps({"dbcs": idx}, indent=1))
    write(os.path.join(OUT, "fingerprints.json"), json.dumps(fps, separators=(",", ":")))
    print("index: %d DBCs -> dbc/index.json; fingerprints (11-bit ids + DLC) -> dbc/fingerprints.json (%d kB)"
          % (len(idx), os.path.getsize(os.path.join(OUT, "fingerprints.json")) // 1024))


