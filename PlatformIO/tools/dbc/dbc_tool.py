def read_dbc_bytes(p):
    """DBCs come as UTF-8 or Windows-1252 (degree signs in units)"""
    raw = open(p, "rb").read()
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return raw.decode("cp1252", errors="replace")


