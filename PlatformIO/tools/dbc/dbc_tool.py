def read_capture(path):
    """-> {id: dlc or None}"""
    text = read(path)
    seen = {}
    if text.lstrip().startswith("{"):
        for fr in json.loads(text).get("frames", []):  # /api/can/recent
            seen[int(fr["id"], 16)] = len(fr.get("data", "").split()) or None
        return seen
    for line in text.splitlines():
        m = re.search(r"\b([0-9A-Fa-f]{3,8})#([0-9A-Fa-f]*)", line)  # candump
        if m:
            seen[int(m.group(1), 16)] = len(m.group(2)) // 2
            continue
        m = re.match(r"\s*(?:0x)?([0-9A-Fa-f]{1,8})\b(?:\s+(\d))?", line)
        if m:
            seen[int(m.group(1), 16)] = int(m.group(2)) if m.group(2) else None
    return seen


def score(seen, fp):
    """explained = share of the bus ids this DBC knows (DLC agreeing where both are known); coverage = share of the
    DBC's ids seen. A car bus shows a subset of a DBC (other buses, other trims), so explained dominates."""
    ids = {mid: dlc for mid, dlc in fp}
    hit = sum(1 for mid, dlc in seen.items() if mid in ids and (dlc is None or ids[mid] == dlc))
    if not seen or not ids:
        return 0.0, 0.0, 0.0
    explained, coverage = hit / len(seen), hit / len(ids)
    return explained * (0.8 + 0.2 * coverage), explained, coverage


def match(path, top=8):
    fps = json.loads(read(os.path.join(OUT, "fingerprints.json")))
    idx = {e["name"]: e for e in json.loads(read(os.path.join(OUT, "index.json")))["dbcs"]}
    seen = read_capture(path)
    ranked = sorted(((score(seen, fp), name) for name, fp in fps.items()), reverse=True)[:top]
    print("%d ids in the capture" % len(seen))
    for (s, ex, cov), name in ranked:
        cars = idx.get(name, {}).get("cars", [])
        print("  %-36s score %.2f  explains %3.0f%% of the bus, %3.0f%% of the DBC  %s"
              % (name, s, ex * 100, cov * 100, ("e.g. " + ", ".join(cars[:3])) if cars else ""))


