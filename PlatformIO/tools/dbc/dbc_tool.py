def car_platforms():
    """dbc name -> [car names] from opendbc/car/<make>/values.py (regex, no opendbc import needed)"""
    car_root = os.path.join(CACHE, "opendbc", "car")
    out = defaultdict(set)
    if not os.path.isdir(car_root):
        return out
    for make in sorted(os.listdir(car_root)):
        vp = os.path.join(car_root, make, "values.py")
        if not os.path.isfile(vp):
            continue
        src = read(vp)
        # config classes and their default dbc: class XPlatformConfig(Parent): dbc_dict ... 'name'
        cls_dbc, parent = {}, {}
        for m in re.finditer(r"^class (\w+)\((\w+)\):(.*?)(?=^\S)", src, re.M | re.S):
            parent[m.group(1)] = m.group(2)
            d = re.search(r"dbc_dict[^\n]*?Bus\.pt:\s*'(\w+)'", m.group(3))
            if d:
                cls_dbc[m.group(1)] = d.group(1)

        def dbc_of(cls):
            while cls and cls not in cls_dbc:
                cls = parent.get(cls)
            return cls_dbc.get(cls)

        # platforms: NAME = SomeConfig( ... ) up to the next platform / end of class
        for m in re.finditer(r"^  ([A-Z0-9_]+) = (\w+)\((.*?)(?=^  [A-Z0-9_]+ = |\Z)", src, re.M | re.S):
            body = m.group(3)
            d = re.search(r"Bus\.pt:\s*'(\w+)'", body) or re.search(r"dbc_dict\(\s*'(\w+)'", body)
            dbc = d.group(1) if d else dbc_of(m.group(2))
            if not dbc:
                continue
            docs = re.findall(r'CarDocs\(\s*"([^"]+)"', body)
            for n in docs or [m.group(1).replace("_", " ").title()]:
                out[dbc].add(n)
    return out


def all_dbc_files():
    for d in ("current", "generated", "legacy", "en"):
        p = os.path.join(OUT, "opendbc", d)
        if os.path.isdir(p):
            for f in sorted(os.listdir(p)):
                if f.endswith(".dbc"):
                    yield d, f, os.path.join(p, f)
    # 0.28.0: the gauge's own DBCs (aftermarket ECUs, written from the makers' published tables - docs/CAN_DBC_plan.md)
    p = os.path.join(OUT, "gauge")
    if os.path.isdir(p):
        for f in sorted(os.listdir(p)):
            if f.endswith(".dbc"):
                yield "gauge", f, os.path.join(p, f)


